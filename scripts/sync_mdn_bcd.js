#!/usr/bin/env node

const fs = require("node:fs");
const path = require("node:path");

const PACKAGE = "@mdn/browser-compat-data";
const DATA_URL = `https://unpkg.com/${PACKAGE}/data.json`;
const PACKAGE_JSON_URL = `https://unpkg.com/${PACKAGE}/package.json`;
const TARGET = path.join(
  process.cwd(),
  "crates/ecma_compat/src/database/mdn_generated.rs",
);
const SYNTAX_FEATURE_SOURCE = path.join(
  process.cwd(),
  "crates/ecma_compat/src/syntax_feature.rs",
);

const RUNTIME_MAPPINGS = [
  ["InternetExplorer", "ie"],
  ["Edge", "edge"],
  ["Firefox", "firefox"],
  ["Chrome", "chrome"],
  ["Safari", "safari"],
  ["Opera", "opera"],
  ["Ios", "safari_ios"],
  ["OperaMobile", "opera_android"],
  ["ChromeAndroid", "chrome_android"],
  ["FirefoxAndroid", "firefox_android"],
  ["SamsungInternet", "samsunginternet_android"],
  ["Node", "nodejs"],
];

main().catch((error) => {
  console.error(error);
  process.exit(1);
});

async function main() {
  const [packageJson, response] = await Promise.all([
    fetchJson(PACKAGE_JSON_URL),
    fetch(DATA_URL),
  ]);
  if (!response.ok) {
    throw new Error(`failed to fetch ${DATA_URL}: ${response.status}`);
  }

  const packageVersion = packageJson.version;
  const data = await response.json();
  const syntaxFeatureKeys = readSyntaxFeatureKeys();
  const allEntries = [];
  collectCompatEntries(data.javascript, ["javascript"], allEntries);

  const entries = allEntries.filter((entry) =>
    syntaxFeatureKeys.has(entry.key),
  );
  const generatedKeys = new Set(entries.map((entry) => entry.key));
  const missingKeys = [...syntaxFeatureKeys].filter(
    (key) => !generatedKeys.has(key),
  );
  if (missingKeys.length > 0) {
    throw new Error(
      `missing MDN BCD entries for syntax features:\n${missingKeys.join("\n")}`,
    );
  }

  entries.sort((left, right) => left.key.localeCompare(right.key));

  fs.writeFileSync(TARGET, renderRust(packageVersion, entries));
  console.log(
    `generated ${entries.length} syntax compat entries from ${PACKAGE}@${packageVersion}`,
  );
  console.log(TARGET);
}

async function fetchJson(url) {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`failed to fetch ${url}: ${response.status}`);
  }

  return response.json();
}

function collectCompatEntries(node, pathParts, entries) {
  if (!node || typeof node !== "object") {
    return;
  }

  if (node.__compat?.support) {
    entries.push({
      key: pathParts.join("."),
      support: node.__compat.support,
    });
  }

  for (const [key, value] of Object.entries(node)) {
    if (key !== "__compat") {
      collectCompatEntries(value, [...pathParts, key], entries);
    }
  }
}

function readSyntaxFeatureKeys() {
  const source = fs.readFileSync(SYNTAX_FEATURE_SOURCE, "utf8");
  const keys = new Set();
  const pattern = /"(?<key>javascript\.[^"]+)"/gu;

  for (const match of source.matchAll(pattern)) {
    keys.add(match.groups.key);
  }

  if (keys.size === 0) {
    throw new Error(
      `no SyntaxFeatureId MDN keys found in ${SYNTAX_FEATURE_SOURCE}`,
    );
  }

  return keys;
}

function renderRust(packageVersion, entries) {
  const lines = [
    "// @generated by scripts/sync_mdn_bcd.js",
    "// Do not edit by hand. Re-run the script after manually reviewing MDN BCD changes.",
    "// Contains only the MDN entries referenced by SyntaxFeatureId.",
    "",
    "use crate::{",
    "  database::SupportRule,",
    "  target::{Runtime, Version},",
    "};",
    "",
    `pub const MDN_BCD_PACKAGE_VERSION: &str = ${JSON.stringify(packageVersion)};`,
    `pub const MDN_BCD_SYNTAX_ENTRY_COUNT: usize = ${entries.length};`,
    "",
    "pub fn support_rule(feature_key: &str, runtime: Runtime) -> SupportRule {",
    "  match feature_key {",
  ];

  for (const entry of entries) {
    lines.push(`    ${JSON.stringify(entry.key)} => match runtime {`);
    for (const [runtime, browser] of RUNTIME_MAPPINGS) {
      lines.push(
        `      Runtime::${runtime} => ${renderSupportRule(entry.support[browser])},`,
      );
    }
    lines.push("      _ => SupportRule::Unknown,");
    lines.push("    },");
  }

  lines.push("    _ => SupportRule::Unknown,");
  lines.push("  }");
  lines.push("}");
  lines.push("");

  return `${lines.join("\n")}\n`;
}

function renderSupportRule(statement) {
  const versionAdded = selectVersionAdded(statement);

  if (versionAdded === true) {
    return "SupportRule::Always";
  }
  if (versionAdded === false) {
    return "SupportRule::Never";
  }
  if (typeof versionAdded !== "string") {
    return "SupportRule::Unknown";
  }

  const atOrBefore = versionAdded.match(/^≤\s*(\d+(?:\.\d+){0,3})$/u);
  if (atOrBefore) {
    return `SupportRule::AtOrBefore(${renderVersion(atOrBefore[1])})`;
  }

  if (/^\d+(?:\.\d+){0,3}$/u.test(versionAdded)) {
    return `SupportRule::Since(${renderVersion(versionAdded)})`;
  }

  return "SupportRule::Unknown";
}

function selectVersionAdded(statement) {
  if (!statement || statement === "mirror") {
    return undefined;
  }

  const statements = Array.isArray(statement) ? statement : [statement];
  const preferred =
    statements.find(
      (item) =>
        item &&
        typeof item === "object" &&
        !item.flags &&
        !item.prefix &&
        !item.alternative_name,
    ) ?? statements[0];

  return preferred?.version_added;
}

function renderVersion(version) {
  const components = version.split(".").map((component) => Number(component));
  while (components.length < 4) {
    components.push(0);
  }

  return `Version::new(${components[0]}, ${components[1]}, ${components[2]}, ${components[3]})`;
}
